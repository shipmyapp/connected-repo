import { z } from "zod";
import { teamMemberRoleZod } from "./enums.zod.js";
import { isReservedTenantSlug, TENANT_SLUG_REGEX } from "./tenant.utils.js";
import { zPhoneNumber, zString, zTimeEpoch, zTimestamps } from "./zod_utils.js";

/**
 * TeamApp Schemas
 */

export const teamAppAutoGeneratedZod = z.object({
	id: z.ulid(),
});

export const teamAppMandatoryZod = z.object({
	name: zString.min(1, "Team name is required"),
});

/** `#rgb` or `#rrggbb`, lower- or upper-case. */
export const zHexColor = zString.regex(
	/^#(?:[0-9a-fA-F]{3}|[0-9a-fA-F]{6})$/,
	"Must be a hex colour like #1976d2",
);

/**
 * Subdomain label of a team's private PWA (`<slug>.<root>`). DNS-label
 * shaped and never one of the reserved platform labels. Lower-cased.
 */
export const zTenantSlug = zString
	.toLowerCase()
	.regex(TENANT_SLUG_REGEX, "3–63 lowercase letters, digits or hyphens; no leading/trailing hyphen")
	.refine((s) => !isReservedTenantSlug(s), { message: "This subdomain is reserved" });

/**
 * Per-team white-label settings. Every field is nullable; unset falls back
 * to `DEFAULT_APP_BRAND` (tenant.utils).
 */
export const teamAppBrandingZod = z.object({
	slug: zTenantSlug.nullable(),
	appName: zString.min(1).max(60).nullable(),
	appShortName: zString.min(1).max(12).nullable(),
	tagline: zString.max(160).nullable(),
	// http(s) only; the server also requires the app's own storage (`updateTeam`).
	pwaIconUrl: z
		.url({ protocol: /^https?$/ })
		.max(2048)
		.nullable(),
	primaryColor: zHexColor.nullable(),
	secondaryColor: zHexColor.nullable(),
	backgroundColor: zHexColor.nullable(),
});
export type TeamAppBranding = z.infer<typeof teamAppBrandingZod>;

export const teamAppOptionalZod = z
	.object({
		logoUrl: z
			.url({ protocol: /^https?$/ })
			.max(2048)
			.nullable(),
		createdByUserId: z.uuid(),
		personalTeamForUserId: z.uuid().nullable(),
		deletedAt: zTimeEpoch.nullable(),
	})
	.extend(teamAppBrandingZod.shape);

export const teamAppCreateInputZod = teamAppMandatoryZod.extend(teamAppOptionalZod.partial().shape);
export type TeamAppCreateInput = z.infer<typeof teamAppCreateInputZod>;

// API-facing create schema. Excludes server-controlled identity/tenancy fields
// (`createdByUserId`, `personalTeamForUserId`, `deletedAt`) so authenticated
// clients can't spoof team ownership or burn another user's personal-team slot
// (soft-delete-partial unique on `personal_team_for_user_id`). The server
// derives `createdByUserId` from the session and never accepts
// `personalTeamForUserId` from clients — it's set only by server-only paths
// (`getDefaultTeam` / `UserTable.afterCreate`).
export const teamAppCreateApiInputZod = teamAppMandatoryZod.extend(
	teamAppOptionalZod.pick({ logoUrl: true }).partial().shape,
);
export type TeamAppCreateApiInput = z.infer<typeof teamAppCreateApiInputZod>;

// Owner/Admin-editable fields: identity + white-label branding. Tenancy
// fields stay server-owned, as on create, and so does the subdomain (ADR-036): the
// operator assigns it from the super-admin console because DNS and the
// certificate are theirs to arrange. The team only reads it. Zod strips an
// unknown `slug` key.
export const teamAppUpdateApiInputZod = teamAppMandatoryZod
	.extend(teamAppOptionalZod.pick({ logoUrl: true }).shape)
	.extend(teamAppBrandingZod.omit({ slug: true }).shape)
	.partial();
export type TeamAppUpdateApiInput = z.infer<typeof teamAppUpdateApiInputZod>;

/** Super-admin: assign (or clear with `null`) a team's subdomain. */
export const teamSlugAssignInputZod = z.object({
	teamId: z.ulid(),
	slug: zTenantSlug.nullable(),
});

export const teamAppSelectAllZod = teamAppMandatoryZod
	.extend(teamAppOptionalZod.shape)
	.extend(teamAppAutoGeneratedZod.shape)
	.extend(zTimestamps);
export type TeamAppSelectAll = z.infer<typeof teamAppSelectAllZod>;

/**
 * Public, unauthenticated projection of a team's branding, keyed by slug.
 * Served to `<slug>.<root>` before sign-in so the login page, manifest and
 * theme can be branded. Deliberately excludes membership/ownership fields.
 */
export const teamBrandingPublicZod = teamAppBrandingZod
	.extend({
		teamId: z.ulid(),
		name: teamAppMandatoryZod.shape.name,
		logoUrl: teamAppOptionalZod.shape.logoUrl,
	})
	.extend({ slug: zTenantSlug });
export type TeamBrandingPublic = z.infer<typeof teamBrandingPublicZod>;

export const teamBrandingLookupInputZod = z.object({ slug: zTenantSlug });
export type TeamBrandingLookupInput = z.infer<typeof teamBrandingLookupInputZod>;

/**
 * TeamMember Schemas
 */

export const teamAppMemberAutoGeneratedZod = z.object({
	id: z.ulid(),
});

export const teamAppMemberMandatoryZod = z.object({
	teamId: z.ulid(),
	role: teamMemberRoleZod,
	addedAt: zTimeEpoch,
});

export const teamAppMemberOptionalZod = z.object({
	userId: z.uuid().nullable(),
	email: z.email().max(320).nullable(),
	phoneNumber: zPhoneNumber.nullable(),
	joinedAt: zTimeEpoch.nullable(),
	deletedAt: zTimeEpoch.nullable(),
});

export const teamAppMemberSelectAllZod = teamAppMemberMandatoryZod
	.extend(teamAppMemberOptionalZod.shape)
	.extend(teamAppMemberAutoGeneratedZod.shape)
	.extend(zTimestamps);
export type TeamAppMemberSelectAll = z.infer<typeof teamAppMemberSelectAllZod>;

export const teamAppMemberRoleZod = teamMemberRoleZod;
export type TeamAppMemberRole = z.infer<typeof teamAppMemberRoleZod>;

// `teamId` is derived from the `x-team-id` header on the RPC procedure, not
// from the request body — callers implicitly add members to their active team.
// An invitation makes an Admin or a Member. Owners are made by an Owner from
// the member list (`teams.updateMemberRole`), never by adding someone.
export const teamInviteRoleZod = z.enum(["Admin", "Member"]);
export type TeamInviteRole = z.infer<typeof teamInviteRoleZod>;

export const teamAppMemberAddInputZod = z
	.object({
		email: z.email().max(320).optional().nullable(),
		phoneNumber: zPhoneNumber.optional().nullable(),
		role: teamInviteRoleZod.default("Member"),
	})
	.refine((data) => data.email || data.phoneNumber, {
		message: "Either email or phone number must be provided",
		path: ["email"],
	});
export type TeamAppMemberAddInput = z.infer<typeof teamAppMemberAddInputZod>;

export const teamWithRoleZod = teamAppSelectAllZod.extend({
	joinedAt: zTimeEpoch.nullable(),
	userRole: teamMemberRoleZod,
});
export type TeamWithRole = z.infer<typeof teamWithRoleZod>;
